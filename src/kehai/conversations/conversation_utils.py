async def safe_websocket_send(websocket_send: WebSocketSend, payload: str) -> None:
    """Send a websocket payload, but don't fail the conversation if the client is gone."""
    try:
        await websocket_send(payload)
    except Exception as e:
        logger.debug(f"Skipping websocket send because the client is unavailable: {e}")


# Convert class methods to standalone functions
def create_batch_input(
    input_text: str,
    images: Optional[List[Dict[str, Any]]],
    from_name: str,
    metadata: Optional[Dict[str, Any]] = None,
    audio: Optional[str] = None,
) -> BatchInput:
    """Create batch input for agent processing.

    `audio` is the spoken turn as a base64 WAV (omni mode, from the server VAD);
    the agent attaches it to the user message when its LLM can hear."""
    return BatchInput(
        texts=[
            TextData(source=TextSource.INPUT, content=input_text, from_name=from_name)
        ],
        images=[
            ImageData(
                source=ImageSource(img["source"]),
                data=img["data"],
                mime_type=img["mime_type"],
            )
            for img in (images or [])
        ]
        if images
        else None,
        audio=AudioData(data=audio) if audio else None,
        metadata=metadata,
    )


async def process_agent_output(
    output: Union[AudioOutput, SentenceOutput],
    character_config: Any,
    live2d_model: Live2dModel,
    tts_engine: TTSInterface,
    websocket_send: WebSocketSend,
    tts_manager: TTSTaskManager,
    translate_engine: Optional[Any] = None,
) -> str:
    """Process agent output with character information and optional translation"""
    output.display_text.name = character_config.character_name
    output.display_text.avatar = character_config.avatar

    full_response = ""
    try:
        if isinstance(output, SentenceOutput):
            full_response = await handle_sentence_output(
                output,
                live2d_model,
                tts_engine,
                websocket_send,
                tts_manager,
                translate_engine,
            )
        elif isinstance(output, AudioOutput):
            full_response = await handle_audio_output(output, websocket_send)
        else:
            logger.warning(f"Unknown output type: {type(output)}")
    except Exception as e:
        logger.error(f"Error processing agent output: {e}")
        await websocket_send(
            json.dumps(
                {"type": "error", "message": f"Error processing response: {str(e)}"}
            )
        )

    return full_response


async def handle_sentence_output(
    output: SentenceOutput,
    live2d_model: Live2dModel,
    tts_engine: TTSInterface,
    websocket_send: WebSocketSend,
    tts_manager: TTSTaskManager,
    translate_engine: Optional[Any] = None,
) -> str:
    """Handle sentence output type with optional translation support"""
    full_response = ""
    async for display_text, tts_text, actions in output:
        logger.debug(f"🏃 Processing output: '''{tts_text}'''...")
        logger.debug(f"🏃 Output actions: {actions.to_dict()}")

        if translate_engine:
            if len(re.sub(r'[\s.,!?，。！？\'"』」）】\s]+', "", tts_text)):
                tts_text = translate_engine.translate(tts_text)
            logger.info(f"🏃 Text after translation: '''{tts_text}'''...")
        else:
            logger.debug("🚫 No translation engine available. Skipping translation.")

        full_response = join_spoken_pieces(full_response, display_text.text)
        await tts_manager.speak(
            tts_text=tts_text,
            display_text=display_text,
            actions=actions,
            live2d_model=live2d_model,
            tts_engine=tts_engine,
            websocket_send=websocket_send,
        )
    return full_response


def join_spoken_pieces(acc: str, piece: str) -> str:
    """Append one spoken piece to the reply text. The divider cuts at commas too and
    each piece arrives left-stripped, so a bare += stored "Thursday,22 October" /
    "Oh,you're glowing" — in the chat history, which is replayed to the model. Put
    the space back between Latin text; CJK runs on without one."""
    if (
        acc
        and piece
        and acc[-1] in ",.!?;:)\u2019\"'"
        and piece[0].isascii()
        # An opening quote too: 'Mm,"they" again.' was stored that way.
        and (piece[0].isalnum() or piece[0] in "\"'(")
    ):
        return f"{acc} {piece}"
    return acc + piece


async def handle_audio_output(
    output: AudioOutput,
    websocket_send: WebSocketSend,
) -> str:
    """Process and send AudioOutput directly to the client"""
    full_response = ""
    async for audio_path, display_text, transcript, actions in output:
        full_response += transcript
        audio_payload = prepare_audio_payload(
            audio_path=audio_path,
            display_text=display_text,
            actions=actions.to_dict() if actions else None,
        )
        await websocket_send(json.dumps(audio_payload))
    return full_response


async def send_conversation_start_signals(websocket_send: WebSocketSend) -> None:
    """Send initial conversation signals"""
    await safe_websocket_send(
        websocket_send,
        json.dumps(
            {
                "type": "control",
                "text": "conversation-chain-start",
            }
        )
    )
    await safe_websocket_send(
        websocket_send, json.dumps({"type": "full-text", "text": "Thinking..."})
    )


async def process_user_input(
    user_input: Union[str, np.ndarray],
    asr_engine: ASRInterface,
    websocket_send: WebSocketSend,
) -> str:
    """Process user input, converting audio to text if needed"""
    if isinstance(user_input, np.ndarray):
        logger.info("Transcribing audio input...")
        try:
            input_text = await asr_engine.async_transcribe_np(user_input)
        except Exception as e:  # noqa: BLE001 — a failed ASR is an empty turn here
            logger.warning(f"ASR failed: {e!r}")
            input_text = ""
        await safe_websocket_send(
            websocket_send,
            json.dumps({"type": "user-input-transcription", "text": input_text})
        )
        return input_text
    return user_input


async def finalize_conversation_turn(
    tts_manager: TTSTaskManager,
    websocket_send: WebSocketSend,
    client_uid: str,
    broadcast_ctx: Optional[BroadcastContext] = None,
) -> None:
    """Finalize a conversation turn"""
    if hasattr(tts_manager, "flush"):
        await tts_manager.flush()  # a short sentence held for merging (Qwen3-TTS)
    if tts_manager.task_list:
        await asyncio.gather(*tts_manager.task_list)
        await safe_websocket_send(
            websocket_send, json.dumps({"type": "backend-synth-complete"})
        )
        # Phase G: the WebRTC track drains server-side — tell the frontend
        # exactly when this turn's audio has finished playing.
        from ..realtime import webrtc_manager
        from ..realtime.webrtc_audio import notify_when_drained
        _track = webrtc_manager.track_for_send(websocket_send)
        if _track is not None:
            asyncio.create_task(
                notify_when_drained(websocket_send, _track)
            )

        response = await message_handler.wait_for_response(
            client_uid, "frontend-playback-complete"
        )

        if not response:
            logger.warning(f"No playback completion response from {client_uid}")
            return

    await safe_websocket_send(
        websocket_send, json.dumps({"type": "force-new-message"})
    )

    if broadcast_ctx and broadcast_ctx.broadcast_func:
        await broadcast_ctx.broadcast_func(
            broadcast_ctx.group_members,
            {"type": "force-new-message"},
            broadcast_ctx.current_client_uid,
        )

    await send_conversation_end_signal(websocket_send, broadcast_ctx)


async def send_conversation_end_signal(
    websocket_send: WebSocketSend,
    broadcast_ctx: Optional[BroadcastContext],
    session_emoji: str = "😊",
) -> None:
    """Send conversation chain end signal"""
    chain_end_msg = {
        "type": "control",
        "text": "conversation-chain-end",
    }

    await safe_websocket_send(websocket_send, json.dumps(chain_end_msg))

    if broadcast_ctx and broadcast_ctx.broadcast_func and broadcast_ctx.group_members:
        await broadcast_ctx.broadcast_func(
            broadcast_ctx.group_members,
            chain_end_msg,
        )

    logger.info(f"😎👍✅ Conversation Chain {session_emoji} completed!")


def cleanup_conversation(tts_manager: TTSTaskManager, session_emoji: str) -> None:
    """Clean up conversation resources"""
    tts_manager.clear()
    logger.debug(f"🧹 Clearing up conversation {session_emoji}.")


